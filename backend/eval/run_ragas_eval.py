"""
RAGAS Evaluation Step 2: Run RAGAS Metrics

Loads eval_results.json (generated by generate_eval_dataset.py) and scores
the RAG pipeline using RAGAS metrics with Gemini as the judge LLM.

Metrics computed:
  - Faithfulness        : Is the answer grounded in retrieved context?
  - Answer Relevancy    : Does the answer address the question?
  - Context Precision   : Are retrieved docs relevant? (best with ground truth)
  - Context Recall      : Were all needed docs retrieved? (needs ground truth)

Run from the backend/ directory:
    python eval/run_ragas_eval.py

Requirements:
    pip install ragas datasets langchain-google-genai
"""

import sys
import json
import math
import asyncio
from pathlib import Path

# Allow imports from backend/ for config
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from config import GEMINI_API_KEY

EVAL_RESULTS_PATH = Path(__file__).parent / "eval_results2.json"
SCORES_OUTPUT_PATH = Path(__file__).parent / "ragas_scores.json"


def run_ragas_evaluation():
    # ── Imports (inside function to give clear error if not installed) ──────
    try:
        from datasets import Dataset
        from ragas import evaluate
        from ragas.metrics import (
            faithfulness,
            answer_relevancy,
            context_precision,
            context_recall,
        )
        from langchain_google_genai import ChatGoogleGenerativeAI, GoogleGenerativeAIEmbeddings
        from ragas.llms import LangchainLLMWrapper
        from ragas.embeddings import LangchainEmbeddingsWrapper
    except ImportError as e:
        print(f"❌ Missing dependency: {e}")
        print("   Run: pip install ragas datasets langchain-google-genai")
        sys.exit(1)

    # ── Load eval results ───────────────────────────────────────────────────
    if not EVAL_RESULTS_PATH.exists():
        print(f"❌ {EVAL_RESULTS_PATH} not found.")
        print("   Run: python eval/generate_eval_dataset.py  first.")
        sys.exit(1)

    print(f"Loading eval results from {EVAL_RESULTS_PATH} ...")
    with open(EVAL_RESULTS_PATH, "r", encoding="utf-8") as f:
        eval_results = json.load(f)

    print(f"Loaded {len(eval_results)} Q&A pairs.")

    # ── Decide which metrics to use ─────────────────────────────────────────
    has_ground_truth = any(r.get("ground_truth") for r in eval_results)

    base_metrics = [faithfulness, answer_relevancy]
    if has_ground_truth:
        base_metrics.extend([context_precision, context_recall])
        print("Ground truth detected — running all 4 metrics.")
    else:
        print("No ground truth provided — running reference-free metrics only")
        print("  (Faithfulness + Answer Relevancy)")

    # ── Build HuggingFace Dataset ───────────────────────────────────────────
    data = {
        "question": [r["question"] for r in eval_results],
        "answer": [r["answer"] for r in eval_results],
        "contexts": [r["contexts"] for r in eval_results],
    }
    if has_ground_truth:
        # Ragas 0.2+ requires 'reference', older versions required 'ground_truth'
        data["reference"] = [r.get("ground_truth", "") or "" for r in eval_results]
        data["ground_truth"] = data["reference"]

    dataset = Dataset.from_dict(data)

    # ── Configure Gemini as judge LLM ────────────────────────────────────────
    print("\nConfiguring Gemini as the RAGAS judge LLM with strict 15 RPM pacing...")
    
    from ragas.run_config import RunConfig

    class RateLimitedGemini(ChatGoogleGenerativeAI):
        async def _agenerate(self, *args, **kwargs):
            # Sleep 5 seconds per call = max 12 RPM (safely below 15 RPM limit)
            await asyncio.sleep(5)
            return await super()._agenerate(*args, **kwargs)

    llm = LangchainLLMWrapper(
        RateLimitedGemini(
            model="gemini-2.0-flash",
            google_api_key=GEMINI_API_KEY,
            temperature=0,
            max_retries=5,
        )
    )
    embeddings = LangchainEmbeddingsWrapper(
        GoogleGenerativeAIEmbeddings(
            model="models/text-embedding-004",
            google_api_key=GEMINI_API_KEY,
        )
    )

    # Attach judge to each metric
    for metric in base_metrics:
        metric.llm = llm
        if hasattr(metric, "embeddings"):
            metric.embeddings = embeddings

    # ── Run evaluation ────────────────────────────────────────────────────────
    print(f"\nRunning RAGAS evaluation on {len(eval_results)} questions...")
    print("This may take a few minutes (one LLM call per question per metric).\n")

    # Limit concurrency to 1 so the 5s sleep forces a strict sequential pace
    # Set a very high timeout (3600s) so queued tasks don't time out while waiting!
    run_config = RunConfig(timeout=3600, max_retries=10, max_workers=1)
    result = evaluate(dataset=dataset, metrics=base_metrics, run_config=run_config)

    # ── Print summary ─────────────────────────────────────────────────────────
    print("\n" + "=" * 60)
    print("RAGAS EVALUATION RESULTS")
    print("=" * 60)


    score_dict = result.to_pandas().mean(numeric_only=True).to_dict()
    for metric_name, score in score_dict.items():
        if math.isnan(score):
            print(f"  {metric_name:<30} NaN")
        else:
            bar = "█" * int(score * 20)
            print(f"  {metric_name:<30} {score:.4f}  {bar}")

    print("=" * 60)

    # ── Save detailed per-question scores ─────────────────────────────────────
    detailed_df = result.to_pandas()
    detailed_df["question"] = [r["question"] for r in eval_results]
    detailed_df["category"] = [r.get("category", "") for r in eval_results]

    scores_out = detailed_df.to_dict(orient="records")
    # Replace NaN with None so json.dump doesn't crash
    def sanitize(obj):
        if isinstance(obj, float) and math.isnan(obj):
            return None
        if isinstance(obj, dict):
            return {k: sanitize(v) for k, v in obj.items()}
        if isinstance(obj, list):
            return [sanitize(v) for v in obj]
        return obj
    scores_out = sanitize(scores_out)
    with open(SCORES_OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(scores_out, f, indent=2, ensure_ascii=False)

    print(f"\n✅ Detailed per-question scores saved to {SCORES_OUTPUT_PATH}")

    # Per-category breakdown
    if "category" in detailed_df.columns:
        print("\nPer-category breakdown:")
        metric_cols = [c for c in detailed_df.columns if c not in ("question", "category", "answer", "contexts", "ground_truth")]
        cat_summary = detailed_df.groupby("category")[metric_cols].mean()
        print(cat_summary.to_string())


if __name__ == "__main__":
    run_ragas_evaluation()
